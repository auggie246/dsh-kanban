import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const root = path.dirname(path.dirname(fileURLToPath(import.meta.url)))
const read = (file) => fs.readFileSync(path.join(root, file), 'utf8').trimEnd()
const helpers = ['frontmatter', 'settings', 'queue', 'execution', 'watch', 'bounce', 'completion', 'import']
  .map((name) => read(`plugin/${name}.js`))
  .join('\n\n')
const hostSource = read('plugin/host.js')
const clientSource = read('plugin/client.js')
const remoteSource = read('permanent/remote.mjs') + '\n'

const hostArtifact = `// Generated by scripts/build-permanent.mjs. Do not edit directly.\nimport { createKanbanController, KanbanGateway } from './remote.mjs'\n\nfunction createKanbanPlugin(register) {\n  const harness = { handle: register }\n\n${helpers}\n\n${hostSource}\n}\n\nconst definition = createKanbanPlugin(() => () => {})\n\nexport const name = 'kanban'\nexport const inject = [...definition.inject, 'typert']\n\nexport async function apply(ctx) {\n  const handlers = new Map()\n  const register = (method, handler) => {\n    if (handlers.has(method)) throw new Error('dsh-kanban: duplicate Host method ' + method)\n    handlers.set(method, handler)\n    return () => handlers.delete(method)\n  }\n  const plugin = createKanbanPlugin(register)\n  await plugin.apply(ctx)\n  new KanbanGateway(ctx, createKanbanController(handlers))\n}\n`

const clientRemote = `
    const PACKAGE = 'dsh-kanban'
    const SERVICE = 'kanban'
    function fail(message) { throw new Error(PACKAGE + ' remote: ' + message) }
    function parseJsonValue(value, label) {
      if (value === null || typeof value === 'string' || typeof value === 'boolean') return value
      if (typeof value === 'number' && Number.isFinite(value)) return value
      if (Array.isArray(value)) return value.map((entry, index) => parseJsonValue(entry, label + '[' + index + ']'))
      if (typeof value === 'object') {
        const copy = {}
        for (const [key, entry] of Object.entries(value)) if (entry !== undefined) copy[key] = parseJsonValue(entry, label + '.' + key)
        return copy
      }
      fail(label + ' must be JSON data')
    }
    function parseJsonObject(value, label) {
      const parsed = parseJsonValue(value, label)
      if (parsed === null || typeof parsed !== 'object' || Array.isArray(parsed)) fail(label + ' must be an object')
      return parsed
    }
    function codec(typeSymbol, parse) {
      return Object.freeze({ mode: 'strict', typeSymbol, schema: Object.freeze({ _zod: {}, parse }) })
    }
    const MethodCodec = codec(PACKAGE + '/Method', (value) => {
      if (typeof value !== 'string' || value === '') fail('method must be a non-empty string')
      return value
    })
    const ArgsCodec = codec(PACKAGE + '/Args', (value) => parseJsonObject(value, 'args'))
    const ResultCodec = codec(PACKAGE + '/Result', (value) => parseJsonObject(value, 'result'))
    const callInvocation = {
      id: PACKAGE + '#' + SERVICE + '/call', service: SERVICE, namespace: SERVICE, method: 'call',
      invocation: { kind: 'direct' },
      parameters: [
        { name: 'method', wire: 'method', source: 'json', codec: MethodCodec },
        { name: 'args', wire: 'args', source: 'json', codec: ArgsCodec },
      ],
      result: ResultCodec,
    }
    const TYPERT_REMOTE = Object.freeze({ package: PACKAGE, descriptors: [callInvocation] })
`

const clientArtifact = `// Generated by scripts/build-permanent.mjs. Do not edit directly.\nwindow.__ModuleLoader__.load({\n  id: 'dsh-kanban',\n  factory: (require) => {\n    const module = { exports: {} }\n    const React = require('react')\n${clientRemote}\n    const inject = ['slots', 'remote']\n\n    function apply(ctx) {\n      const host = {\n        call(method, args = {}) {\n          const target = ctx.get('remote.' + SERVICE)\n          if (target === undefined || typeof target.call !== 'function') {\n            return Promise.resolve({ ok: false, error: 'Board service is still initializing. Try again in a moment.' })\n          }\n          return target.call(method, args)\n        },\n      }\n      const styles = {\n        insert(css) {\n          let element\n          ctx.effect(() => {\n            if (typeof document === 'undefined') return () => {}\n            element = document.createElement('style')\n            element.textContent = css\n            document.head.append(element)\n            return () => element.remove()\n          }, 'dsh-kanban: browser styles')\n          return () => { if (element !== undefined) element.remove() }\n        },\n      }\n      ctx.effect(async () => {\n        const disposeRemote = await ctx.remote.$mount(TYPERT_REMOTE)\n        return async () => { await disposeRemote() }\n      }, 'dsh-kanban: remote bridge')\n      const plugin = (() => {\n${clientSource}\n      })()\n      return plugin.apply(ctx)\n    }\n\n    module.exports.apply = apply\n    module.exports.inject = inject\n    return module.exports\n  },\n})\n`

const outputs = new Map([
  ['lib/index.mjs', hostArtifact],
  ['lib/client.js', clientArtifact],
  ['lib/remote.mjs', remoteSource],
])

const checking = process.argv.includes('--check')
let stale = false
for (const [file, content] of outputs) {
  const target = path.join(root, file)
  if (checking) {
    if (!fs.existsSync(target) || fs.readFileSync(target, 'utf8') !== content) {
      console.error(`${file} is stale; run npm run build:permanent`)
      stale = true
    }
  } else {
    fs.mkdirSync(path.dirname(target), { recursive: true })
    fs.writeFileSync(target, content)
  }
}
if (stale) process.exitCode = 1
